pub fn allowed(group: u16, element: u16) -> bool {
    ALLOWED_TAGS.contains(&(((group as u32) << 16) | element as u32))
}
pub fn placeholder(value: &str) -> bool {
    matches!(value.trim().trim_end_matches('\0').to_uppercase().as_str(), "" | "ANON" | "ANONYMOUS" | "ANONYMISED" | "ANONYMIZED" | "REDACTED" | "SYNTHETIC^TEST" | "SYN-0001")
}
#[cfg(test)]
mod tests {
    use super::*;
    #[test] fn identity_and_unknown_fields_are_not_whitelisted() {
        for (g,e) in [(0x0010,0x0030),(0x0008,0x0050),(0x0008,0x0090),(0x0011,0x0010),(0x0008,0x1030)] { assert!(!allowed(g,e)); }
        for (g,e) in [(0x0020,0x000D),(0x0020,0x0032),(0x5200,0x9230),(0x7FE0,0x0010)] { assert!(allowed(g,e)); }
    }
    #[test] fn identity_replacements_are_placeholders_only() {
        for value in ["DOE^JANE", "ACC12345", "19700101", "Synthetic Test Author"] { assert!(!placeholder(value)); }
        for value in ["", "ANON", "ANONYMOUS", "SYNTHETIC^TEST", "SYN-0001"] { assert!(placeholder(value)); }
    }
}
