import { expect, test } from '@playwright/test';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import path from 'node:path';
import { authorCaptureCase, localCaptures, localJournal, snapshot } from '../support/captureFixture';
import { replayRuns } from '../support/replayFixture';
import { matchesView } from '../../lib/journal/match';
test('M8 one CT series, one take, one finding: capture → retained extraction → edit/approve → exact replay', async ({ page, browser }) => {
  test.setTimeout(120000);
  const { caseId, orgId } = await authorCaptureCase(page);
  await page.getByRole('button', { name: 'Start recording', exact: true }).first().click();
  await expect.poll(async () => {
    const local = (await localCaptures(page))[0]; if (!local) return false;
    const journal = await localJournal(page, local.manifest.sessionId);
    return ['audio', 'video'].every(stream => journal.some(e => e.kind === 'discontinuity' && e.payload?.stream === stream && ['media_start', 'permission_delay'].includes(String(e.payload?.reason))));
  }).toBe(true);
  await page.locator('[data-viewer-snapshot] canvas').first().click({ position: { x: 100, y: 100 } });
  await expect(page.getByTestId('pending-markers')).toContainText('1 retained markers');
  await page.waitForTimeout(2100); // retain actual synthetic microphone samples, not just an empty start chunk
  await page.getByRole('button', { name: 'Finish recording', exact: true }).click();
  await expect.poll(async () => (await localCaptures(page))[0]?.synced, { timeout: 20000 }).toBe(true);
  const capture = (await localCaptures(page))[0], journal = await localJournal(page, capture.manifest.sessionId);
  const renders = journal.filter(e => e.kind === 'render');
  expect(renders.length).toBeGreaterThan(0); expect(new Set(renders.map(e => e.snapshot!.seriesUID)).size).toBe(1);
  await page.getByLabel('I reviewed the captured images, audio and viewport video and found no patient identifiers.').check();
  await page.getByRole('button', { name: 'Save media review' }).click();
  await expect(page.getByText('Media PHI review recorded.')).toBeVisible();
  await promisify(execFile)(process.execPath, ['--import', 'tsx', 'e2e/support/extractionReplayFixtureSetup.ts', orgId, caseId, capture.manifest.sessionId], { cwd: process.cwd(), env: { ...process.env, MONGODB_URI: '', DICOMWEB_BACKEND: 'orthanc', ORTHANC_URL: '', DATA_DIR: path.join(process.cwd(), '.radlearn-tmp', 'radlearn-data') } });
  await page.getByRole('button', { name: 'Process and teach case', exact: true }).click();
  await expect(page.getByText('Draft findings ready — 1 candidate. Review the evidence before approval.')).toBeVisible();
  const data = await (await page.request.get(`/api/cases/${caseId}`)).json(); expect(data.findings).toHaveLength(1);
  const findingId = data.findings[0].id, card = page.getByTestId(`finding-review-${findingId}`), endpoint = `/api/cases/${caseId}/findings/${findingId}/replay`;
  expect((await page.request.get(endpoint)).status()).toBe(409);
  const anonymous = await browser.newContext(); expect((await anonymous.request.get(endpoint)).status()).toBe(401); expect((await anonymous.request.post(endpoint, { data: {} })).status()).toBe(401); await anonymous.close();
  await card.getByLabel('Description').fill('Expert reviewed the exact synthetic contour.');
  await card.getByRole('button', { name: 'Save new version', exact: true }).click();
  await expect(card.getByText('Version 2', { exact: true })).toBeVisible();
  await card.getByRole('button', { name: 'Jump', exact: true }).click();
  await expect(card.getByText('Rendered ✓', { exact: true })).toBeVisible();
  await card.getByRole('button', { name: 'Approve v2', exact: true }).click();
  await expect(card.getByText('Approved v2', { exact: true })).toBeVisible();
  await card.getByRole('button', { name: 'Replay approved take', exact: true }).click();
  const panel = page.getByRole('region', { name: 'Exact replay', exact: true });
  await panel.getByRole('button', { name: 'Start exact replay' }).click();
  await expect(panel).toContainText('Exact replay complete.', { timeout: 20000 });
  await expect(panel).toContainText('Replay receipt saved.');
  const run = (await replayRuns(page, caseId))[0]; expect(run.version).toBe(2); expect(run.captureSessionId).toBe(capture.manifest.sessionId); expect(run.misses).toHaveLength(0);
  expect(run.confirmations.filter(c => c.seq !== null).map(c => c.seq)).toEqual(renders.map(e => e.seq));
  for (const e of renders) expect(matchesView(run.confirmations.find(c => c.seq === e.seq)!.snapshot, e.snapshot!)).toBe(true);
  expect(matchesView(await snapshot(page), renders.at(-1)!.snapshot!)).toBe(true);
  const geometry = JSON.parse((await page.locator('[data-replay-geometry]').getAttribute('data-replay-geometry'))!);
  expect(geometry).toHaveLength(1); expect(geometry[0].imagePoints[0]).toEqual(journal.find(e => e.kind === 'marker')!.payload!.imagePoint);
  await test.info().attach('roundtrip-receipt', { body: JSON.stringify(run), contentType: 'application/json' });
  await page.screenshot({ path: test.info().outputPath('capture-extract-approve-replay.png'), fullPage: true });
});
