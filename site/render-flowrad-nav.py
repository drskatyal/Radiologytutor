"""Render the shared FlowRad products menu and footer. Use --check in CI.

Copied from drskatyal/flowrad-viewer-site (scripts/render-flowrad-nav.py) when the
marketing site moved into this app. shared/flowrad-nav.json is byte-identical to the
copy in flowrad-landing (pinned by shared/flowrad-nav.sha256). Instead of patching
static HTML pages, it writes components/site/flowradNav.generated.ts, which the
Next.js site header and footer render.
"""
import argparse
import json
from html import escape
from pathlib import Path

parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
root = Path(__file__).resolve().parent
repo = root.parent
spec = json.loads((root / 'shared/flowrad-nav.json').read_text())
products = {p['id']: p for p in spec['products']}

def link(p, description=False):
    current = ' aria-current="page"' if p.get('id') == 'viewer' else ''
    badge = ' <em>Beta</em>' if p.get('badge') else ''
    desc = f' <span>{escape(p["desc"])}</span>' if description else ''
    return f'<a href="{escape(p["url"], quote=True)}"{current}>{escape(p["label"])}{badge}{desc}</a>'

nav = '<nav class="fr-switch" aria-label="FlowRad products">\n  <details><summary>Products</summary>\n    <ul>\n'
nav += ''.join(f'      <li>{link(p, True)}</li>\n' for p in products.values())
nav += '    </ul>\n  </details>\n</nav>\n'
footer = '<footer class="fr-footer"><div class="fr-columns">\n'
for column in spec['footer']['columns']:
    footer += f'<div><h2>{escape(column["title"])}</h2><ul>'
    for item in column['links']:
        footer += '<li>' + link(products[item] if isinstance(item, str) else item) + '</li>'
    footer += '</ul></div>\n'
footer += f'</div><p>{escape(spec["footer"]["legal"])}</p></footer>'

outputs = {root / 'shared/flowrad-nav.html': nav + '<!-- footer: render the three columns from flowrad-nav.json the same way -->\n'}
generated = repo / 'components/site/flowradNav.generated.ts'
outputs[generated] = (
    '// GENERATED by site/render-flowrad-nav.py from site/shared/flowrad-nav.json. Do not edit.\n'
    f'export const FLOWRAD_NAV_HTML = {json.dumps(nav.rstrip())};\n'
    f'export const FLOWRAD_FOOTER_HTML = {json.dumps(footer)};\n'
)
for path, content in outputs.items():
    if args.check:
        if path.read_text() != content:
            raise SystemExit(f'{path.name} is out of date; run python3 site/render-flowrad-nav.py')
    else:
        path.write_text(content)
