#!/usr/bin/env node
// Build the offline voice recognizer's worker as a real script file:
//   public/voice/recognizer-worker.js           (web)
//   desktop/public/voice/recognizer-worker.js   (desktop, bundled in the installer)
//
// Why a file and not vosk-browser's own worker: vosk-browser starts its worker
// from a blob: URL, and a blob: worker inherits the page's Content-Security-
// Policy. The recognizer is Emscripten + embind, and embind builds functions
// with `new Function` — which the desktop CSP (script-src 'self'
// 'wasm-unsafe-eval') forbids. The worker then failed inside LoadVosk, posted
// an "error" message nobody listened to (vosk-browser's createModel only waits
// for "load"), and the mic button spun forever. A worker loaded from its own
// URL takes the policy of its own response; Tauri sends CSP only with HTML,
// so the recognizer runs and the app's CSP stays strict.
//
// The source is vosk-browser's worker, byte for byte, with four checked
// patches (each must match exactly once or this script fails):
//   1. download progress is posted to the page ({event:"progress"}), so the
//      UI shows a real progress bar instead of a spinner;
//   2–3. no IndexedDB persistence (IDBFS): the model is extracted into memory.
//      Persisting it doubled the storage, failed outright where IndexedDB is
//      small or absent ("Failed to sync file system"), and the archive is
//      local (desktop) or HTTP-cached (web) anyway;
//   4. errors that are not Error objects (Emscripten rejects with strings)
//      still reach the page with their text.
//
// Run by `npm run build` / `npm run dev` (pre-scripts) in both apps. Output is
// git-ignored with the model (public/voice/).

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(path.join(root, "package.json"));
const bundle = readFileSync(require.resolve("vosk-browser/dist/vosk.js"), "utf8");
const match = bundle.match(/createBase64WorkerFactory\('([A-Za-z0-9+/=]+)'/);
if (!match) {
  console.error("build-voice-worker: vosk-browser's embedded worker was not found (package changed?)");
  process.exit(1);
}
let source = Buffer.from(match[1], "base64").toString("utf8");

const patches = [
  [
    "bytesWritten=bytesWritten+value.length;",
    'bytesWritten=bytesWritten+value.length;self.postMessage({event:"progress",loaded:bytesWritten,total:length||0});',
  ],
  ["this.Vosk.FS.mount(this.Vosk.IDBFS, {}, storagePath);", "/* FlowRad: in-memory only, no IDBFS */"],
  ["return this.Vosk.syncFilesystem(true);", "return undefined;"],
  ["return this.Vosk.syncFilesystem(false);", "return undefined;"],
  [
    'ctx.postMessage({ event: "error", error: error.message });',
    'ctx.postMessage({ event: "error", error: (error && error.message) || String(error) });',
  ],
];
for (const [from, to] of patches) {
  const count = source.split(from).length - 1;
  if (count !== 1) {
    console.error(`build-voice-worker: expected one "${from.slice(0, 60)}", found ${count}`);
    process.exit(1);
  }
  source = source.replace(from, to);
}

const header = "/* FlowRad offline voice recognizer worker — generated by scripts/build-voice-worker.mjs from vosk-browser (Apache-2.0). */\n";
for (const out of [path.join(root, "public", "voice", "recognizer-worker.js"), path.join(root, "desktop", "public", "voice", "recognizer-worker.js")]) {
  mkdirSync(path.dirname(out), { recursive: true });
  writeFileSync(out, header + source);
}
console.log(`build-voice-worker: wrote recognizer-worker.js (${(source.length / 1e6).toFixed(1)} MB) for web and desktop`);
